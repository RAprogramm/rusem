//! Tense, mood and person: when an action is put and by whom.

/// Verbal tense.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum Tense {
    /// Past.
    Past,
    /// Present.
    Present,
    /// Future.
    Future
}

/// Verbal mood.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum Mood {
    /// Indicative.
    Indicative,
    /// Imperative.
    Imperative
}

/// Grammatical person.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum Person {
    /// First person.
    First,
    /// Second person.
    Second,
    /// Third person.
    Third
}
